def escape_markdown_v2(text: str) -> str:
    """
    Экранирует спецсимволы для Telegram MarkdownV2.
    Мы экранируем только те знаки, которые ИИ чаще всего забывает закрыть:
    точки, восклицательные знаки, дефисы и скобки.
    """
    # Список символов для экранирования
    escape_chars = r'()[]{}#!.+-=|'
    return re.sub(f'([{re.escape(escape_chars)}])', r'\\\1', text)


async def get_ai_response(history):
    """
    Основная функция получения ответа от ИИ с учетом истории и форматирования.
    """
    headers = {
        "Content-Type": "application/json",
        "Authorization": f'Bearer {API_KEY}',
    }

    # Системная инструкция (Личность Джарвиса и правила разметки)
    system_prompt = {
        "role": "system",
        "content": (
            "Ты — ИИ-ассистент в стиле Джарвиса из фильма 'Железный человек'.\n\n"

            "СТИЛЬ (ОБЯЗАТЕЛЬНО):\n"
            "- Обращайся к пользователю: 'Сэр'.\n"
            "- Тон: Спокойный, уверенный, интеллектуальный.\n"
            "- Пиши лаконично, короткими абзацами.\n\n"

            "ПРАВИЛА ФОРМАТИРОВАНИЯ (MarkdownV2):\n"
            "- Используй *жирный шрифт* для акцентов.\n"
            "- Используй `моноширинный текст` для команд или терминов.\n"
            "- Используй > для цитат.\n"
            "- ВАЖНО: Если используешь символы . ! - ( ) в тексте, "
            "всегда ставь перед ними обратный слэш, например: 1\\. или Привет\\!.\n"
            "- ЗАПРЕЩЕНО использовать таблицы.\n\n"

            "ПОВЕДЕНИЕ:\n"
            "- Если Сэр просит план или список, делай его через экранированный дефис: \\- .\n"
            "- Сначала давай краткий ответ, затем детали."
        )
    }

    # Объединяем системную роль и историю диалога
    full_messages = [system_prompt] + history

    # Вызываем функцию автоматического выбора модели (из вашего файла models.py)
    response_data = await get_best_model_response(full_messages, headers)

    if response_data is None:
        return "⏳ Сэр, все вычислительные модули сейчас перегружены. Прошу подождать минуту."

    try:
        # Извлекаем текст ответа из JSON
        ai_text = response_data['choices'][0]['message']['content']

        if not ai_text:
            return "Сэр, произошла ошибка: ответ пуст."

        # ПРИМЕНЯЕМ ЭКРАНИРОВАНИЕ
        # Это защитит бота от падения, если ИИ забудет экранировать точку или восклицание
        formatted_text = escape_markdown_v2(ai_text)

        return formatted_text

    except (KeyError, IndexError) as e:
        print(f"❌ Ошибка парсинга JSON: {e}")
        return "Сэр, мои аналитические системы дали сбой при разборе ответа."
    except Exception as e:
        print(f"❌ Непредвиденная ошибка: {e}")
        return "Сэр, произошла непредвиденная ошибка в моем ядре."