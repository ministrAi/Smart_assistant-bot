from config import API_KEY, LLM_API_URL
import httpx
from models import get_best_model_response


async def get_ai_response(history):
    headers = {
        "Content-Type": "application/json",
        "Authorization": f'Bearer {API_KEY}',
    }

    # Добавляем системную инструкцию в начало списка сообщений
    system_prompt = {
        "role": "system",
        "content": (
            "Ты — ИИ-ассистент в стиле Джарвиса из фильма 'Железный человек'.\n\n"

            "СТИЛЬ (ОБЯЗАТЕЛЬНО):\n"
            "- Обращайся к пользователю: 'Сэр'\n"
            "- Спокойный, уверенный, интеллектуальный тон\n"
            "- Короткие абзацы\n"
            "- Логичное объяснение шаг за шагом\n\n"

            "ФОРМАТ TELEGRAM (HTML-разметка):\n"
            "- Разделяй текст пустыми строками\n"
            "- Используй эмодзи умеренно (🔹 💡 ⚙️)\n"
            "- Используй <b>жирный шрифт</b> для акцентов\n"
            "- Используй <i>курсив</i> для терминов\n"
            "- Используй <code>моноширинный шрифт</code> для команд\n"
            "- Используй <pre>блок кода</pre> для многострочного кода\n"
            "- Используй <u>подчёркивание</u> для важного\n"
            "- Используй <s>зачёркнутый текст</s> если нужно\n"
            "- Для списков используй • или цифры с точкой\n"
            "- НЕ используй Markdown-символы (*, _, `, ~)\n"
            "- Экранируй HTML-теги если они в тексте: &lt; &gt; &amp;\n\n"

            "ПОВЕДЕНИЕ:\n"
            "- Объясняй как наставник, а не как учебник\n"
            "- Сначала краткий ответ, затем пояснение\n\n"

            "ПРИМЕР СТИЛЯ:\n"
            "Сэр, различие заключается в следующем...\n"
            "Позвольте пояснить...\n"
        )
    }

    # Объединяем системную роль и историю
    full_messages = [system_prompt] + history

    # Используем автоматический выбор модели
    response_data = await get_best_model_response(full_messages, headers)

    if response_data is None:
        return "⏳ Все ИИ-модели временно перегружены. Попробуйте через минуту."

    try:
        # Извлекаем текст ответа
        ai_text = response_data['choices'][0]['message']['content']

        if not ai_text or ai_text.strip() == "":
            return "🤔 AI не смог сформировать ответ. Попробуйте переформулировать вопрос."

        return ai_text

    except (KeyError, IndexError):
        print(f"⚠️ Неожиданная структура ответа: {response_data}")
        return "ИИ вернул неверный формат ответа."