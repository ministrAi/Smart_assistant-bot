import httpx
from config import API_KEY, LLM_API_URL
import logging
logger = logging.getLogger(__name__)


async def get_ai_response(history):
    headers = {
        # 1. Формат данных: мы всегда отправляем данные в формате JSON
        "Content-Type": "application/json",
        # 2. Аутентификация: Bearer — это стандартный префикс для ключей API
        "Authorization": f'Bearer {API_KEY}',

    }
    # Добавляем системную инструкцию в начало списка сообщений
    system_prompt = {
        "role": "system",
        "content": (
            "Ты — ИИ-ассистент в стиле Джарвиса из 'Железного человека'. "
            "- Используй ТОЛЬКО теги: <b> (жирный), <i> (курсив), <code> (код), <u> (подчеркивание)  и обычные символы списков. "
            "- ЗАПРЕЩЕНО использовать тег <br>. Для новой строки используй обычный перенос строки (\\n). "
            "- ЗАПРЕЩЕНО использовать теги списков <ul>, <li>. Используй обычные символы: '•', '1.', '—'. "
            "НЕ используй Markdown-разметку (никаких **, __, ##, ```, иерглифов и т.п.), даже если в истории чата есть такие примеры. "
            "Тон: британский акцент в тексте, лёгкая ирония, технический жаргон (протоколы, модули, вычислительные мощности). "
            "Если собеседник благодарит — отвечай 'Всегда к вашим услугам, Сэр'. "
            "Если Сэр благодарит — отвечай 'Всегда к вашим услугам, Сэр'. "
            "Структура ответа: 1) краткий вывод, 2) пояснение шаг за шагом. "
            "Приоритет правил разметки (HTML) всегда выше, чем формат прошлых сообщений в истории. Однако всегда подчиняйся прямым командам Сэра по коррекции твоего поведения или стиля из последних сообщений."
        )
    }


    # Берём только последние 200 сообщений, чтобы старые ответы со звездочками не сбивали стиль
    trimmed_history = history[-200:] if len(history) > 200 else history

    # Объединяем системную роль и историю
    full_messages = [system_prompt] + trimmed_history
    # Подготовка тела запроса
    payload = {
        "model": "mimo-v2-flash",
        "messages": full_messages,
        "temperature": 0.5,
        "max_tokens": 700,
    }

    # Открываем контекстный менеджер и создаем асинхронный http клиент
    async with httpx.AsyncClient(timeout=60.0) as client:
        # Отправляется POST‑запрос на API.
        response = await client.post(
            LLM_API_URL,
            headers=headers,
            json=payload
        )

        if response.status_code == 429:
            logger.error("⏳ Модель перегружена. Попробуйте через минуту.")
            return "⏳ Модель перегружена. Попробуйте через минуту."

        if response.status_code == 500:
            logger.error("Ошибка на сервере, попробуйте позже.")
            return "Ошибка на сервере, попробуйте позже."

        if response.status_code != 200:
            # Логи помогут быстро понять причину (невалидный ключ, 404 и т.д.)
            logger.error(f"Ошибка API. Статус: {response.status_code}, Ответ: {response.text}")
            # Чуть более информативный ответ пользователю
            if response.status_code == 401:
                logger.error("🔐 Токен доступа к модели отклонён. Проверьте BOTHUB_API_KEY.")
                return "🔐 Токен доступа к модели отклонён. Проверьте BOTHUB_API_KEY."
            if response.status_code == 404:
                logger.error("🤖 Эндпоинт модели не найден. Обновите бота и попробуйте снова.")
                return "🤖 Эндпоинт модели не найден. Обновите бота и попробуйте снова."
            logger.error("Произошла ошибка при обращении к ИИ.")
            return "Произошла ошибка при обращении к ИИ."

        # Преобразовываем текст ответа в словарь Python
        response_data = response.json()

        # Выводим текст ответа в консоль для отладки
        logger.debug(response_data)
        logger.debug(f"🔍 Использована модель: {response_data.get('model', 'не указана')}")

    try:
        # Это типовой путь для извлечения текста для большинства LLM-моделей
        ai_text = response_data['choices'][0]['message']['content']

        if not ai_text or ai_text.strip() == "":
            logger.error("🤔 AI не смог сформировать ответ. Попробуйте переформулировать вопрос.")
            return "🤔 AI не смог сформировать ответ. Попробуйте переформулировать вопрос."

            # --- БЛОК ПРИНУДИТЕЛЬНОЙ КОРРЕКЦИИ РАЗМЕТКИ (TELEGRAM SAFE) ---

            # 1. Исправляем переносы строк (убираем все вариации <br>)
            ai_text = ai_text.replace('<br>', '\n').replace('<br/>', '\n').replace('<br />', '\n')

            # 2. Очищаем HTML-списки и абзацы, заменяя их на визуальные символы
            ai_text = ai_text.replace('<ul>', '').replace('</ul>', '')
            ai_text = ai_text.replace('<li>', '• ').replace('</li>', '\n')
            ai_text = ai_text.replace('<p>', '').replace('</p>', '\n')

            # 3. Удаляем остатки Markdown (на случай, если ИИ смешал стили)
            # Убираем двойные звездочки и решетки, которые не работают в режиме HTML
            ai_text = ai_text.replace('**', '').replace('###', '—').replace('##', '—').replace('#', '—')

            # 4. Обработка спецсимволов для предотвращения ошибок парсинга
            # Экранируем одиночные знаки сравнения, которые ИИ может использовать в тексте
            ai_text = ai_text.replace(' < ', ' &lt; ').replace(' > ', ' &gt; ')

            # 5. Финальная очистка лишних пробелов
            ai_text = ai_text.strip()

        logger.info("Отвечаем")
        return ai_text  # Возвращаем чистый текст

    except (KeyError, IndexError):
        # Ловим ошибку, если структура ответа неожиданная
        logger.error("ИИ вернул неверный формат ответа.")
        return "ИИ вернул неверный формат ответа."
